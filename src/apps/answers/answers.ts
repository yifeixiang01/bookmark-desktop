export function nextAnswer(current: number | null, random = Math.random(), recent: readonly number[] = []) {
  const excluded = new Set([...recent.slice(-32), ...(current === null ? [] : [current])])
  const available = ANSWERS.map((_, index) => index).filter(index => !excluded.has(index))
  const pool = available.length ? available : ANSWERS.map((_, index) => index).filter(index => index !== current)
  return pool[Math.floor(Math.max(0, Math.min(.999999, random)) * pool.length)]
}
