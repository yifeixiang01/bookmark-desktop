param([Parameter(Mandatory=$true)][string]$ArchivePath)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem
$source = (Resolve-Path -LiteralPath $ArchivePath).Path
$zip = [System.IO.Compression.ZipFile]::OpenRead($source)
try {
  $entry = $zip.GetEntry('manifest.json')
  if ($null -eq $entry) { throw 'ZIP must contain manifest.json at its root.' }
  $reader = New-Object System.IO.StreamReader($entry.Open(), [System.Text.Encoding]::UTF8)
  try { $manifest = $reader.ReadToEnd() | ConvertFrom-Json } finally { $reader.Dispose() }
  if ($manifest.name -ne 'Stashy' -or $manifest.version -notmatch '^\d+\.\d+\.\d+(\.\d+)?$') { throw 'Invalid Stashy manifest or version.' }
} finally { $zip.Dispose() }
$projectRoot = Split-Path $PSScriptRoot -Parent
$name = 'Stashy-' + $manifest.version + '.zip'
$downloads = Join-Path $projectRoot 'public/downloads'
New-Item -ItemType Directory -Force -Path $downloads | Out-Null
$destination = Join-Path $downloads $name
Copy-Item -LiteralPath $source -Destination $destination -Force
$release = [ordered]@{ version = $manifest.version; url = '/downloads/' + $name; bytes = (Get-Item -LiteralPath $destination).Length; sha256 = (Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash.ToLowerInvariant() }
$content = '// Generated by scripts/import-stashy-release.ps1 from the packaged manifest.' + [Environment]::NewLine + 'export const STASHY_RELEASE = ' + ($release | ConvertTo-Json) + ' as const' + [Environment]::NewLine
[System.IO.File]::WriteAllText((Join-Path $projectRoot 'src/lib/stashyRelease.ts'), $content, (New-Object System.Text.UTF8Encoding($false)))
Write-Output ('Imported ' + $name)
